#!/bin/bash
# User-level bootstrap (runs as dev on every container start, called from
# entrypoint.sh). Declarative and idempotent: every step checks the real
# artifact instead of a marker file, so a failed install is simply retried
# on the next start. To add a user-space tool to the environment, add a
# guarded step here — never bake it into /home/dev in the Dockerfile (the
# home volume is only seeded from the image once).
set -uo pipefail

DOTFILES_DIR="$HOME/workspace/dotfiles"
FAILED=()

log()  { echo "[bootstrap] $*"; }
fail() { echo "[bootstrap] WARNING: $2" >&2; FAILED+=("$1"); }

# 1. Symlinks into the dotfiles repo (always; idempotent)
bash "$DOTFILES_DIR/scripts/setup-symlinks.sh" \
  || fail symlinks "setup-symlinks.sh failed"

# 2. Personal git identity: docker/.env (GIT_USER_NAME / GIT_USER_EMAIL) is
#    the source of truth; regenerate on every start so .env edits win.
if [ -n "${GIT_USER_NAME:-}" ] && [ -n "${GIT_USER_EMAIL:-}" ]; then
  printf '# Generated by docker/bootstrap.sh from docker/.env — edit that file instead.\n[user]\n\tname = %s\n\temail = %s\n' \
    "$GIT_USER_NAME" "$GIT_USER_EMAIL" > "$HOME/.gitconfig.local"
elif [ ! -f "$HOME/.gitconfig.local" ]; then
  fail gitconfig "GIT_USER_NAME / GIT_USER_EMAIL not set in docker/.env and ~/.gitconfig.local missing — git commits will have no identity"
fi

# 3. zinit: copy the image-side seed into the persistent home
if [ ! -f "$HOME/.local/share/zinit/zinit.zsh" ]; then
  log "Seeding zinit from /opt/zinit..."
  rm -rf "$HOME/.local/share/zinit"
  cp -a /opt/zinit "$HOME/.local/share/zinit" \
    || fail zinit "could not copy /opt/zinit"
fi

# 4. Claude Code (self-updating, lives in the home volume)
if [ ! -x "$HOME/.local/bin/claude" ]; then
  log "Installing Claude Code (first run)..."
  curl -fsSL https://claude.ai/install.sh | bash \
    || fail claude "installer failed (will retry on next start)"
fi

# 4b. Claude Code MCP servers (user scope, stored in ~/.claude.json). The
#     check asks claude itself, so a removed or failed registration is redone.
#     excel-mcp-server runs via uvx (fetched into the uv cache on first use)
#     and may only touch workbooks under ~/workspace (the Windows bind mount).
if [ -x "$HOME/.local/bin/claude" ] \
   && ! "$HOME/.local/bin/claude" mcp get excel >/dev/null 2>&1; then
  log "Registering excel MCP server for Claude Code..."
  "$HOME/.local/bin/claude" mcp add excel --scope user -- \
    uvx excel-mcp-server stdio --allow-dir "$HOME/workspace" >/dev/null \
    || fail mcp-excel "claude mcp add excel failed (will retry on next start)"
fi

# 5. Antigravity CLI (binary name: agy)
if [ ! -x "$HOME/.local/bin/agy" ]; then
  log "Installing Antigravity CLI (first run)..."
  curl -fsSL https://antigravity.google/cli/install.sh | bash \
    || fail antigravity "installer failed (will retry on next start)"
fi

# 5b. Installers append PATH lines to ~/.zshrc, which is a symlink into the
#     dotfiles repo — strip them again so the repo stays clean. PATH already
#     covers ~/.local/bin at the top of .zshrc. --follow-symlinks keeps the
#     symlink intact (plain sed -i would replace it with a regular file).
if grep -q '^# Added by Antigravity CLI installer' "$HOME/.zshrc" 2>/dev/null; then
  log "Stripping installer-appended lines from .zshrc..."
  sed -i --follow-symlinks '/^# Added by Antigravity CLI installer$/,+1d' "$HOME/.zshrc" \
    || fail zshrc-cleanup "could not strip installer lines from .zshrc"
fi

# 6. Neovim plugins (headless; verbose output goes to a log file)
if [ ! -d "$HOME/.local/share/nvim/lazy" ]; then
  NVIM_LOG="$HOME/.local/state/bootstrap-nvim.log"
  log "Bootstrapping Neovim plugins (first run, log: $NVIM_LOG)..."
  nvim --headless "+Lazy! sync" +qa >"$NVIM_LOG" 2>&1 \
    || fail nvim-plugins "Lazy sync failed (see $NVIM_LOG)"
  log "Installing Treesitter parsers..."
  nvim --headless '+lua require("nvim-treesitter").install({"lua","vim","vimdoc","json","yaml","toml","bash","markdown","markdown_inline","python","typescript","tsx","javascript","html","css","dockerfile","gitcommit","diff","regex","query"})' '+sleep 120' +qa >>"$NVIM_LOG" 2>&1 \
    || fail treesitter "parser install failed (see $NVIM_LOG)"
fi

# 7. tmux plugins (per-plugin check so a partial failure heals itself). The
#    list comes from the `@plugin` lines in .tmux.conf, and each plugin is
#    cloned into the directory TPM derives from it (the repo basename, e.g.
#    catppuccin/tmux -> ~/.tmux/plugins/tmux). TPM silently skips a plugin it
#    cannot find there, so any other directory name means it never loads.
TMUX_CONF="$DOTFILES_DIR/tmux/.tmux.conf"
TMUX_PLUGINS=$(grep -oP "^set -g @plugin '\K[^']+" "$TMUX_CONF") \
  || fail tmux-plugins "no @plugin lines found in $TMUX_CONF"
while IFS='#' read -r repo branch; do
  [ -n "$repo" ] || continue
  dir="${repo##*/}"
  [ -d "$HOME/.tmux/plugins/$dir" ] && continue
  log "Cloning tmux plugin $repo..."
  git clone ${branch:+-b "$branch"} "https://github.com/$repo" "$HOME/.tmux/plugins/$dir" \
    || fail tmux-plugins "clone of $repo failed"
done <<<"$TMUX_PLUGINS"

if [ ${#FAILED[@]} -gt 0 ]; then
  log "Finished with warnings: ${FAILED[*]}"
  exit 1
fi
log "OK"
